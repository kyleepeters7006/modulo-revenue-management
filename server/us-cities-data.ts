/**
 * Look up city-level coordinates from a full address string.
 *
 * Parses patterns like:
 *   "123 Main St, Byron Center, MI 49315"  →  "byron center,mi"
 *   "Byron Center, MI 49315"               →  "byron center,mi"
 *   "Byron Center, MI"                     →  "byron center,mi"
 *
 * When an exact city match fails, strips trailing type-code suffixes
 * (e.g. "Springfield FG" → "Springfield", "Liberty Township" → "Liberty")
 * and retries. This handles internal location-code suffixes that appear
 * in city fields of the database.
 *
 * Returns null if no match is found in the dataset.
 */
export function lookupCityCoords(address: string): LatLng | null {
  if (!address) return null;

  const norm = address.trim();

  // Match patterns like: "City, ST 12345" or "City, ST" at end of string
  // Also handles "City ST 12345" without comma between city and state
  const patterns = [
    /,\s*([A-Za-z][A-Za-z\s'()-]+),\s*([A-Z]{2})(?:\s+\d{5}(?:-\d{4})?)?(?:\s*$|,)/,
    /,\s*([A-Za-z][A-Za-z\s'()-]+)\s+([A-Z]{2})(?:\s+\d{5}(?:-\d{4})?)?(?:\s*$|,)/,
    /^([A-Za-z][A-Za-z\s'()-]+),\s*([A-Z]{2})(?:\s+\d{5}(?:-\d{4})?)?$/,
    /^([A-Za-z][A-Za-z\s'()-]+)\s+([A-Z]{2})(?:\s+\d{5}(?:-\d{4})?)?$/,
  ];

  for (const pattern of patterns) {
    const m = norm.match(pattern);
    if (!m) continue;

    const rawCity = m[1].trim();
    const state = m[2].trim().toLowerCase();

    // 1. Exact city match
    const exactKey = `${rawCity.toLowerCase()},${state}`;
    if (US_CITIES[exactKey]) return US_CITIES[exactKey];

    // 2. Strip trailing short uppercase codes (e.g. "FG", "SL", "HC", "MC")
    //    and common geographic suffixes ("Township", "Twp", "County")
    const suffixStripped = rawCity
      .replace(/\s+(?:Township|Twp|County|Twsp)\s*$/i, '')
      .replace(/\s+[A-Z]{1,3}\s*$/, '')
      .trim();

    if (suffixStripped && suffixStripped !== rawCity) {
      const strippedKey = `${suffixStripped.toLowerCase()},${state}`;
      if (US_CITIES[strippedKey]) {
        return US_CITIES[strippedKey];
      }
    }

    // 3. If city contains parenthetical (e.g. "Dexter (Scio Township)"), try the
    //    part before the parenthesis
    const parenStripped = rawCity.replace(/\s*\([^)]*\)\s*$/, '').trim();
    if (parenStripped && parenStripped !== rawCity) {
      const parenKey = `${parenStripped.toLowerCase()},${state}`;
      if (US_CITIES[parenKey]) return US_CITIES[parenKey];
    }
  }

  return null;
}
